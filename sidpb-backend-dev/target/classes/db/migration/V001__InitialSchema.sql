CREATE TABLE regiao (
    id_regiao        INTEGER PRIMARY KEY,
    sigla            VARCHAR(2)   NOT NULL,
    nome             VARCHAR(100) NOT NULL,
    latitude_regiao  NUMERIC(10,7),
    longitude_regiao NUMERIC(10,7),

    CONSTRAINT uq_regiao_sigla
        UNIQUE (sigla),

    CONSTRAINT uq_regiao_nome
        UNIQUE (nome),

    CONSTRAINT ck_regiao_sigla
        CHECK (sigla ~ '^[A-Z]{1,2}$'),

    CONSTRAINT ck_regiao_coordenadas_preenchidas_em_par
        CHECK (
            (latitude_regiao IS NULL AND longitude_regiao IS NULL)
            OR
            (latitude_regiao IS NOT NULL AND longitude_regiao IS NOT NULL)
        ),

    CONSTRAINT ck_regiao_latitude
        CHECK (
            latitude_regiao IS NULL
            OR latitude_regiao BETWEEN -90 AND 90
        ),

    CONSTRAINT ck_regiao_longitude
        CHECK (
            longitude_regiao IS NULL
            OR longitude_regiao BETWEEN -180 AND 180
        )
);

CREATE TABLE estado (
