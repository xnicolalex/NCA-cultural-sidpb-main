CREATE TABLE categoria_hospedeiro (
    id_categoria    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_categoria  VARCHAR(100) NOT NULL,

    CONSTRAINT uq_categoria_hospedeiro_nome
        UNIQUE (nome_categoria)
);

CREATE TABLE hospedeiro (
    id_hospedeiro   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cientifico VARCHAR(200) NOT NULL UNIQUE,
    id_categoria    INTEGER NOT NULL,

    CONSTRAINT fk_hospedeiro_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categoria_hospedeiro (id_categoria)
);

CREATE TABLE caracteristica (
    id_caracteristica    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_caracteristica  VARCHAR(200) NOT NULL UNIQUE,

    CONSTRAINT uq_caracteristica_nome
        UNIQUE (nome_caracteristica)
);

CREATE TABLE categoria_caracteristica (
    id_categoria       INTEGER NOT NULL,
    id_caracteristica  INTEGER NOT NULL,

    CONSTRAINT pk_categoria_caracteristica
        PRIMARY KEY (id_categoria, id_caracteristica),

    CONSTRAINT fk_categoria_caracteristica_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categoria_hospedeiro (id_categoria)
        ON DELETE CASCADE,

    CONSTRAINT fk_categoria_caracteristica_caracteristica
        FOREIGN KEY (id_caracteristica)
        REFERENCES caracteristica (id_caracteristica)
        ON DELETE CASCADE
);

CREATE TABLE doenca (
    id_doenca       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cientifico VARCHAR(200) NOT NULL UNIQUE,
    sinonimos       JSONB NOT NULL DEFAULT '[]'::JSONB,

    CONSTRAINT ck_doenca_sinonimos_array
        CHECK (jsonb_typeof(sinonimos) = 'array')
);

CREATE TABLE parasito (
    id_parasito      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cientifico  VARCHAR(200) NOT NULL UNIQUE,
    ordem_taxonomica VARCHAR(100)
);

CREATE TABLE vetor (
    id_vetor        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cientifico VARCHAR(200) NOT NULL UNIQUE,
    sinonimos       JSONB NOT NULL DEFAULT '[]'::JSONB,

    CONSTRAINT ck_vetor_sinonimos_array
        CHECK (jsonb_typeof(sinonimos) = 'array')
);

CREATE TABLE doenca_parasito (
    id_doenca   INTEGER NOT NULL,
    id_parasito INTEGER NOT NULL,

    CONSTRAINT pk_doenca_parasito
        PRIMARY KEY (id_doenca, id_parasito),

    CONSTRAINT fk_doenca_parasito_doenca
        FOREIGN KEY (id_doenca)
        REFERENCES doenca (id_doenca)
        ON DELETE CASCADE,

    CONSTRAINT fk_doenca_parasito_parasito
        FOREIGN KEY (id_parasito)
        REFERENCES parasito (id_parasito)
        ON DELETE CASCADE
);

CREATE TABLE vetor_parasito (
    id_vetor    INTEGER NOT NULL,
    id_parasito INTEGER NOT NULL,

    CONSTRAINT pk_vetor_parasito
        PRIMARY KEY (id_vetor, id_parasito),

    CONSTRAINT fk_vetor_parasito_vetor
        FOREIGN KEY (id_vetor)
        REFERENCES vetor (id_vetor)
        ON DELETE CASCADE,

    CONSTRAINT fk_vetor_parasito_parasito
        FOREIGN KEY (id_parasito)
        REFERENCES parasito (id_parasito)
        ON DELETE CASCADE
);

CREATE TABLE fonte (
    id_fonte   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fonte VARCHAR(200),
    tipo_fonte VARCHAR(100),
    titulo     VARCHAR(500),
    autores    JSONB NOT NULL DEFAULT '[]'::JSONB,
    url        VARCHAR(1000),
    data       DATE,

    CONSTRAINT ck_fonte_autores_array
        CHECK (jsonb_typeof(autores) = 'array')
);

CREATE TABLE ocorrencia (
    id_ocorrencia         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data                  DATE,
    parte_corpo           VARCHAR(255),
    tratamento            VARCHAR(255),
    desfecho              VARCHAR(300),
    idade_hospedeiro      VARCHAR(50),
    sexo_hospedeiro       VARCHAR(30),
    estagio_vida_parasito VARCHAR(100),

    id_hospedeiro INTEGER NOT NULL,
    id_doenca     INTEGER NOT NULL,
    id_parasito   INTEGER NOT NULL,
    id_vetor      INTEGER,
    id_local      INTEGER NOT NULL,

    CONSTRAINT fk_ocorrencia_hospedeiro
        FOREIGN KEY (id_hospedeiro)
        REFERENCES hospedeiro (id_hospedeiro),

    CONSTRAINT fk_ocorrencia_doenca
        FOREIGN KEY (id_doenca)
        REFERENCES doenca (id_doenca),

    CONSTRAINT fk_ocorrencia_parasito
        FOREIGN KEY (id_parasito)
        REFERENCES parasito (id_parasito),

    CONSTRAINT fk_ocorrencia_vetor
        FOREIGN KEY (id_vetor)
        REFERENCES vetor (id_vetor),

    CONSTRAINT fk_ocorrencia_local
        FOREIGN KEY (id_local)
        REFERENCES local (id_local),

    -- Garante que o parasito informado esteja associado à doença.
    CONSTRAINT fk_ocorrencia_doenca_parasito
        FOREIGN KEY (id_doenca, id_parasito)
        REFERENCES doenca_parasito (id_doenca, id_parasito),

    -- Se houver vetor, garante que ele esteja associado ao parasito.
    -- Com id_vetor NULL, a restrição não é aplicada.
    CONSTRAINT fk_ocorrencia_vetor_parasito
        FOREIGN KEY (id_vetor, id_parasito)
        REFERENCES vetor_parasito (id_vetor, id_parasito)
);

CREATE TABLE ocorrencia_fonte (
    id_ocorrencia INTEGER NOT NULL,
    id_fonte      INTEGER NOT NULL,

    CONSTRAINT pk_ocorrencia_fonte
        PRIMARY KEY (id_ocorrencia, id_fonte),

    CONSTRAINT fk_ocorrencia_fonte_ocorrencia
        FOREIGN KEY (id_ocorrencia)
        REFERENCES ocorrencia (id_ocorrencia)
        ON DELETE CASCADE,

    CONSTRAINT fk_ocorrencia_fonte_fonte
        FOREIGN KEY (id_fonte)
        REFERENCES fonte (id_fonte)
        ON DELETE CASCADE
);

